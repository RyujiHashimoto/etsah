"""Convert MCP and OpenAI tool lists into Etsah ``op`` declarations.

The importer writes source text. It does not check the result. Every effect
it adds is marked in a comment:

- ``inferred`` — an annotation hint was true
- ``review`` — a name matched, or a hint was missing and the op would otherwise look pure
- ``declared`` — the tool JSON listed ``effects``, which are copied as written

False hints add nothing. A missing hint is not treated as the opposite
effect. Edit the ``eff`` line to override; comments do not change the check.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Optional


class ToolImportError(Exception):
    """The tool JSON cannot be converted. The message names the tool when it has one."""


_EFFECT_KINDS = ("read", "write", "net", "spend", "emit")
_EFFECT_RE = re.compile(r"([A-Za-z_]\w*)\s*\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)\Z")
_EMIT_WORDS = ("send", "email", "post")
_SPEND_WORDS = ("pay", "charge")
# A token matches when it is the word, or the word plus one of these suffixes.
# ``payment`` matches ``pay``. ``payload`` does not.
_SUFFIXES = frozenset({"", "s", "es", "ed", "ing", "ment", "ments", "er", "ers"})
_SCALARS = {"string": "String", "integer": "Int", "number": "Decimal", "boolean": "Bool"}
_BUILTINS = frozenset({"Int", "String", "Bool", "Date", "Decimal"})

_HEADERS = {
    "mcp": (
        "# Generated by `etsah import mcp` from an MCP tool list.",
        "# inferred: the effect comes from an annotation hint. Edit the eff line to change it.",
        "# review: the effect or the gap was guessed from the tool name or from a missing hint.",
        "# declared: the tool JSON listed effects, and those are used as written.",
        "# Comments do not change the check. Change the eff line to override.",
    ),
    "openai": (
        "# Generated by `etsah import openai` from OpenAI function-calling tools.",
        "# inferred: the effect comes from an annotation hint. Edit the eff line to change it.",
        "# review: the effect or the gap was guessed from the tool name or from a missing hint.",
        "# declared: the tool JSON listed effects, and those are used as written.",
        "# Comments do not change the check. Change the eff line to override.",
    ),
}


def import_mcp(data: Any) -> str:
    """Convert an MCP tools/list document, a tool list, or one tool object."""
    return _render("mcp", _normalize_mcp(data))


def import_openai(data: Any) -> str:
    """Convert OpenAI function-calling tools (nested ``function`` or flat)."""
    return _render("openai", _normalize_openai(data))


def render_file(kind: str, path: str) -> str:
    """Read JSON at ``path`` and convert it. Missing files raise ``OSError``."""
    if kind not in _HEADERS:
        raise ToolImportError(f"unknown import kind {kind!r}")
    text = Path(path).read_text(encoding="utf-8")
    try:
        data = json.loads(text)
    except json.JSONDecodeError as ex:
        raise ToolImportError(f"invalid JSON in {path}: {ex.msg} (line {ex.lineno})") from ex
    if kind == "mcp":
        return import_mcp(data)
    return import_openai(data)


def _render(kind: str, tools: list[dict[str, Any]]) -> str:
    lines = list(_HEADERS[kind])
    if not tools:
        lines.extend(["", "# review: the tool list was empty.", ""])
        return "\n".join(lines) + "\n"
    types: list[str] = []
    seen_types: set[str] = set()
    blocks: list[list[str]] = []
    seen_ops: set[str] = set()
    for index, tool in enumerate(tools, 1):
        op_lines, op_types = _render_tool(tool, index)
        op_name = op_lines[0].split("(", 1)[0].removeprefix("op ").strip()
        if op_name in seen_ops:
            raise ToolImportError(f"duplicate op name {op_name!r}")
        seen_ops.add(op_name)
        for type_name in op_types:
            if type_name not in seen_types:
                seen_types.add(type_name)
                types.append(type_name)
        blocks.append(op_lines)
    lines.append("")
    if types:
        lines.extend(f"type {name}" for name in types)
        lines.append("")
    for block in blocks:
        lines.extend(block)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _render_tool(tool: dict[str, Any], index: int) -> tuple[list[str], list[str]]:
    raw_name = tool.get("name")
    if not isinstance(raw_name, str) or not raw_name.strip():
        raise ToolImportError(f"tool {index} is missing a name")
    op_name = _op_name(raw_name, index)
    description = tool.get("description")
    if description is None or description == "":
        title = _annotation_title(tool)
        doc = title or raw_name.strip()
        missing_doc = title is None
    else:
        if not isinstance(description, str):
            raise ToolImportError(f"{raw_name}: description must be a string")
        doc = description.strip() or raw_name.strip()
        missing_doc = description.strip() == ""
    schema = _input_schema(tool, raw_name)
    params, type_names, schema_notes = _parameters(op_name, schema)
    ret, ret_type, ret_notes = _return_type(op_name, tool.get("outputSchema"))
    if ret_type:
        type_names.append(ret_type)
    effects, effect_notes = _effects(tool, op_name, raw_name)
    notes: list[str] = []
    if op_name != raw_name.strip():
        notes.append(f"review: tool name {raw_name!r} was renamed to {op_name}")
    if missing_doc:
        notes.append("review: description was missing; doc is the tool name")
    notes.extend(ret_notes)
    notes.extend(schema_notes)
    notes.extend(effect_notes)
    params_text = ", ".join(f"{name}: {typ}" for name, typ in params)
    lines = [f"op {op_name}({params_text}) -> {ret}"]
    lines.append(f"  doc {json.dumps(doc, ensure_ascii=False)}")
    for note in notes:
        lines.append(f"  # {note}")
    if effects:
        rendered = ", ".join(f"{kind}({target})" for kind, target in effects)
        lines.append(f"  eff {rendered}")
    lines.append("  impl native")
    return lines, type_names


def _annotation_title(tool: dict[str, Any]) -> Optional[str]:
    annotations = tool.get("annotations")
    if not isinstance(annotations, dict):
        return None
    title = annotations.get("title")
    if isinstance(title, str) and title.strip():
        return title.strip()
    return None


def _input_schema(tool: dict[str, Any], raw_name: str) -> dict[str, Any]:
    schema = tool.get("inputSchema", tool.get("input_schema", tool.get("parameters")))
    if schema is None:
        return {}
    if not isinstance(schema, dict):
        raise ToolImportError(f"{raw_name}: input schema must be an object")
    return schema


def _parameters(op_name: str, schema: dict[str, Any]) -> tuple[list[tuple[str, str]], list[str], list[str]]:
    notes: list[str] = []
    properties = schema.get("properties", {})
    if properties is None:
        properties = {}
    if not isinstance(properties, dict):
        raise ToolImportError(f"{op_name}: input schema properties must be an object")
    if not properties:
        if schema and schema.get("type") not in (None, "object"):
            notes.append("review: input schema has no properties; the op takes no parameters")
        elif "$ref" in schema:
            notes.append("review: input schema uses $ref; parameters were not expanded")
        return [], [], notes
    required = schema.get("required", [])
    if required is None:
        required = []
    if not isinstance(required, list):
        raise ToolImportError(f"{op_name}: input schema required must be a list")
    required_names = {item for item in required if isinstance(item, str)}
    omitted = [name for name in properties if name not in required_names]
    if omitted:
        notes.append(
            "review: JSON Schema required omits "
            + ", ".join(omitted)
            + "; Etsah parameters are all required"
        )
    params: list[tuple[str, str]] = []
    type_names: list[str] = []
    used: set[str] = set()
    for raw_prop, prop_schema in properties.items():
        if not isinstance(raw_prop, str) or not raw_prop.strip():
            raise ToolImportError(f"{op_name}: a property name is missing")
        name = _param_name(raw_prop, used)
        used.add(name)
        if name != raw_prop:
            notes.append(f"review: parameter {raw_prop!r} was renamed to {name}")
        etsah_type, opaque, prop_notes = _param_type(op_name, name, prop_schema)
        notes.extend(prop_notes)
        if opaque:
            type_names.append(opaque)
        params.append((name, etsah_type))
    return params, type_names, notes


def _param_type(op_name: str, name: str, schema: Any) -> tuple[str, Optional[str], list[str]]:
    notes: list[str] = []
    if not isinstance(schema, dict):
        return "String", None, [f"review: parameter {name} has no JSON schema; used String"]
    notes.extend(_schema_type_notes(schema, f"parameter {name}"))
    kind = _json_type(schema)
    if kind in _SCALARS:
        return _SCALARS[kind], None, notes
    if kind in {"object", "array"} or "properties" in schema:
        type_name = _opaque_name(op_name, name)
        shown = kind or "object"
        notes.append(f"review: parameter {name} has JSON type {shown}; imported as opaque type {type_name}")
        return type_name, type_name, notes
    notes.append(f"review: parameter {name} has no JSON type; used String")
    return "String", None, notes


def _return_type(op_name: str, schema: Any) -> tuple[str, Optional[str], list[str]]:
    if schema is None:
        return "String", None, ["review: return type String is a placeholder; the tool JSON has no output schema"]
    if not isinstance(schema, dict):
        raise ToolImportError(f"{op_name}: outputSchema must be an object")
    notes = _schema_type_notes(schema, "outputSchema")
    kind = _json_type(schema)
    if kind in _SCALARS:
        return _SCALARS[kind], None, notes
    if kind in {"object", "array"} or "properties" in schema:
        type_name = _opaque_name(op_name, "result")
        shown = kind or "object"
        note = f"review: outputSchema is {shown}; imported as opaque type {type_name}"
        return type_name, type_name, [*notes, note]
    return "String", None, [*notes, "review: return type String is a placeholder; outputSchema has no type"]


def _schema_type_notes(schema: dict[str, Any], label: str) -> list[str]:
    raw = schema.get("type")
    if not isinstance(raw, list):
        return []
    notes: list[str] = []
    if "null" in raw:
        notes.append(f"review: {label} allows null; Etsah has no null so the declared type stays non-null")
    types = list(dict.fromkeys(item for item in raw if isinstance(item, str) and item != "null"))
    if len(types) > 1:
        notes.append(
            f"review: {label} allows multiple JSON types ({', '.join(types)}); Etsah has no union types, "
            f"so the declaration uses the first non-null type ({types[0]})"
        )
    return notes


def _json_type(schema: dict[str, Any]) -> str:
    raw = schema.get("type", "")
    if isinstance(raw, list):
        non_null = [item for item in raw if item != "null" and isinstance(item, str)]
        return non_null[0] if non_null else ""
    if isinstance(raw, str):
        return raw
    return ""


def _effects(
    tool: dict[str, Any],
    op_name: str,
    raw_name: str,
) -> tuple[list[tuple[str, str]], list[str]]:
    notes: list[str] = []
    annotations = tool.get("annotations") or {}
    if not isinstance(annotations, dict):
        raise ToolImportError(f"{raw_name}: annotations must be an object")
    if annotations.get("readOnlyHint") is True and annotations.get("destructiveHint") is True:
        notes.append("review: readOnlyHint and destructiveHint are both true; keep the effect that is actually true")
    if "idempotentHint" in annotations:
        notes.append("review: idempotentHint is not an effect and was not imported")
    hits = _name_hits(raw_name)
    declared = tool.get("effects", None)
    if declared is not None:
        effects = _parse_declared(declared, raw_name)
        rendered = ", ".join(f"{kind}({target})" for kind, target in effects)
        notes.append(f"declared: effects were taken from the tool JSON: {rendered}")
        declared_set = set(effects)
        for keyword, kind, target in hits:
            suggestion = f"{kind}({target})"
            if (kind, target) in declared_set:
                notes.append(f"review: name matches {keyword} -> {suggestion}; already declared")
            else:
                notes.append(f"review: name matches {keyword} -> {suggestion}; not applied because effects were declared")
        return effects, notes
    effects: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()

    def add(kind: str, target: str, note: str) -> None:
        effect = (kind, target)
        if effect not in seen:
            effects.append(effect)
            seen.add(effect)
        notes.append(note)

    if annotations.get("readOnlyHint") is True:
        add("read", op_name, f"inferred: readOnlyHint -> read({op_name})")
    if annotations.get("destructiveHint") is True:
        add("write", op_name, f"inferred: destructiveHint -> write({op_name})")
    if annotations.get("openWorldHint") is True:
        add(
            "net",
            op_name,
            "inferred: openWorldHint -> net("
            + op_name
            + "). Change this to emit if the tool sends a message instead of calling a host.",
        )
    for keyword, kind, target in hits:
        add(kind, target, f"review: name matches {keyword} -> {kind}({target})")
    if not effects:
        notes.append("review: no effect was inferred. This op stays pure until you add an eff line.")
    return effects, notes


def _parse_declared(effects: Any, raw_name: str) -> list[tuple[str, str]]:
    if not isinstance(effects, list) or not effects:
        raise ToolImportError(f"{raw_name}: effects must be a non-empty list of kind(target) strings")
    parsed: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for item in effects:
        if not isinstance(item, str):
            raise ToolImportError(f"{raw_name}: effect {item!r} must be a string like read(tickets)")
        matched = _EFFECT_RE.fullmatch(item.strip())
        if matched is None:
            raise ToolImportError(f"{raw_name}: effect {item!r} must look like kind(target)")
        kind, target = matched.group(1), matched.group(2)
        if kind not in _EFFECT_KINDS:
            raise ToolImportError(f"{raw_name}: unknown effect kind {kind!r}")
        effect = (kind, target)
        if effect in seen:
            raise ToolImportError(f"{raw_name}: duplicate effect {kind}({target})")
        seen.add(effect)
        parsed.append(effect)
    return parsed


def _name_hits(raw_name: str) -> list[tuple[str, str, str]]:
    hits: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for token in _tokens(raw_name):
        for keyword in _EMIT_WORDS:
            if keyword not in seen and _matches(token, keyword):
                hits.append((keyword, "emit", "mail"))
                seen.add(keyword)
        for keyword in _SPEND_WORDS:
            if keyword not in seen and _matches(token, keyword):
                hits.append((keyword, "spend", "payment"))
                seen.add(keyword)
    return hits


def _tokens(name: str) -> list[str]:
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    spaced = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", spaced)
    return [part.lower() for part in re.split(r"[^A-Za-z]+", spaced) if part]


def _matches(token: str, keyword: str) -> bool:
    if not token.startswith(keyword):
        return False
    return token[len(keyword):] in _SUFFIXES


def _op_name(raw: str, index: int) -> str:
    chars: list[str] = []
    for ch in raw.strip():
        if ("A" <= ch <= "Z") or ("a" <= ch <= "z") or ch.isdigit() or ch in "._":
            chars.append(ch)
        else:
            chars.append("_")
    text = re.sub(r"_+", "_", "".join(chars)).strip("._")
    if not text:
        raise ToolImportError(f"tool {index} name {raw!r} cannot be an op name")
    if text[0].isdigit():
        text = "tool_" + text
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*", text) is None:
        raise ToolImportError(f"tool {index} name {raw!r} cannot be an op name")
    return text


def _param_name(raw: str, used: set[str]) -> str:
    chars: list[str] = []
    for ch in raw.strip():
        if ("A" <= ch <= "Z") or ("a" <= ch <= "z") or ch.isdigit() or ch == "_":
            chars.append(ch)
        else:
            chars.append("_")
    text = re.sub(r"_+", "_", "".join(chars)).strip("_")
    if not text or text[0].isdigit():
        text = "arg_" + text if text else "arg"
    if text in {"true", "false"}:
        text = text + "_value"
    base = text
    suffix = 2
    while text in used:
        text = f"{base}_{suffix}"
        suffix += 1
    return text


def _opaque_name(op_name: str, suffix: str) -> str:
    parts = _tokens(op_name) + _tokens(suffix)
    if not parts:
        name = "Value"
    else:
        name = "".join(part[:1].upper() + part[1:] for part in parts)
    if name in _BUILTINS or name[0].isdigit():
        name = name + "Value"
    return name


def _normalize_mcp(data: Any) -> list[dict[str, Any]]:
    items = _tool_items(data, "MCP JSON must be a tool, a list of tools, or an object with a tools list")
    tools: list[dict[str, Any]] = []
    for index, item in enumerate(items, 1):
        if not isinstance(item, dict):
            raise ToolImportError(f"MCP tool {index} must be an object")
        tools.append(item)
    return tools


def _normalize_openai(data: Any) -> list[dict[str, Any]]:
    items = _tool_items(
        data,
        "OpenAI JSON must be a tool, a list of tools, or an object with a tools list",
    )
    tools: list[dict[str, Any]] = []
    for index, item in enumerate(items, 1):
        if not isinstance(item, dict):
            raise ToolImportError(f"OpenAI tool {index} must be an object")
        function = item.get("function")
        if isinstance(function, dict):
            tool = dict(function)
            if "annotations" in item and "annotations" not in tool:
                tool["annotations"] = item["annotations"]
            if "effects" in item and "effects" not in tool:
                tool["effects"] = item["effects"]
            tools.append(tool)
            continue
        tools.append(item)
    return tools


def _tool_items(data: Any, message: str) -> list[Any]:
    if isinstance(data, list):
        return data
    if isinstance(data, dict) and "tools" in data:
        items = data["tools"]
        if not isinstance(items, list):
            raise ToolImportError("tools must be a list")
        return items
    if isinstance(data, dict) and ("name" in data or "function" in data or data.get("type") == "function"):
        return [data]
    raise ToolImportError(message)


